function showConfirmation() {
    const confirmationStep = data.confirmation;

    for (let i = 0; i < confirmationStep.title.length; i++) {
        setTimeout(function () {
            handleDelay(confirmationStep.title[i]);
        }, i * 500);
    }

    setTimeout(function () {
        showOptions(confirmationStep.options);
    }, confirmationStep.title.length * 500);
}


function showOptions(options){
    for(var i=0;i<options.length;i++){
        var opt= document.createElement("span");
        var inp= '<div>'+options[i]+'</div>';
        opt.innerHTML=inp;
        opt.setAttribute("class","opt");
        opt.addEventListener("click", handleOpt);
        cbot.appendChild(opt);
        handleScroll();
    }
}

function handleOpt() {
    console.log(this);
    var str = this.innerText;
    var textArr = str.split(" ");
    var findText = textArr[0];

    document.querySelectorAll(".opt").forEach((el) => {
        el.remove();
    });
    var elm = document.createElement("p");
    elm.setAttribute("class", "test");
    var sp = '<span class="rep">' + this.innerText + '</span>';
    elm.innerHTML = sp;
    cbot.appendChild(elm);

    console.log(findText.toLowerCase());
    var tempObj = data[findText.toLowerCase()];

    // Vérifier si l'utilisateur a cliqué sur "Lundi"
    if (findText.toLowerCase() === "lundi" && tempObj.formulaire) {
        // Afficher le formulaire pour "Lundi"
        setTimeout(function () {
            showForm(tempObj);
        }, tempObj.title.length * 500);
    } else {
        // Afficher les options normales
        handleResults(tempObj.title, tempObj.options, tempObj.url);
    }
}


function handleDelay(title){
    var elm= document.createElement("p");
        elm.innerHTML= title;
        elm.setAttribute("class","msg");
        cbot.appendChild(elm);
}


function handleResults(title, options, url) {
    for (let i = 0; i < title.length; i++) {
        setTimeout(function () {
            handleDelay(title[i]);
        }, i * 500);
    }

    const isObjectEmpty = (url) => {
        return JSON.stringify(url) === "{}";
    };

    if (isObjectEmpty(url) == true) {
        console.log("having more options");
        setTimeout(function () {
            showOptions(options);
        }, title.length * 500);
    } else if (url.formulaire) {
        console.log("afficher le formulaire");
        setTimeout(function () {
            showForm(url);
        }, title.length * 500);
    } else {
        console.log("end result");
        setTimeout(function () {
            handleOptions(options, url);
        }, title.length * 500);
    }
}

