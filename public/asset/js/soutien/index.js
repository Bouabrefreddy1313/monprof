function addBackButton() {
    const backButton = document.createElement("div");
    backButton.innerHTML = `
        <div class="back-option">
            <i class="back-arrow">←</i>
            <span>Retour au choix précédent</span>
        </div>
    `;
    backButton.classList.add("back-btn-container");
    backButton.style.display = "none"; // Caché par défaut
    backButton.addEventListener("click", handleBackButton);
    cbot.appendChild(backButton);
}
// Mise à jour de la fonction handleBackButton
function handleBackButton() {
  if (chatHistory.length > 0) {
    choice.pop();
    const previousState = chatHistory.pop();
    cbot.innerHTML = '';

    // Afficher les messages précédents
    previousState.messages.forEach(msg => {
      const elm = document.createElement("p");
      elm.innerHTML = msg.content;
      elm.setAttribute("class", msg.class);
      cbot.appendChild(elm);
    });

    // Réafficher les options précédentes
    showOptions(previousState.options);

    // Afficher le bouton retour uniquement s'il y a d'autres états précédents
    if (chatHistory.length > 0) {
      addBackButton();
      document.querySelector(".back-btn-container").style.display = "block";
    } else {
      // Cacher le bouton retour s'il n'y a plus d'états précédents
      document.querySelector(".back-btn-container").style.display = "none";
    }
  }
  handleScroll();
}


